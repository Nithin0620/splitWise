const Invitation = require('../models/Invitation');
const Trip = require('../models/Trip');
const User = require('../models/User');
const { sendInviteEmail } = require('../utils/email');
const { publishTripEvent } = require('../config/ably');

// ─── Send Invite ──────────────────────────────────────────────────────────────

// @desc    Send a trip invitation email to an address
// @route   POST /api/invites/trips/:tripId
// @access  Private (trip owner)
const sendInvite = async (req, res) => {
  const { email } = req.body;

  if (!email) {
    return res.status(400).json({ message: 'email is required' });
  }

  const normalizedEmail = email.toLowerCase().trim();

  // Load trip
  const trip = await Trip.findById(req.params.tripId)
    .populate('createdBy', 'name email avatar')
    .populate('members', 'name email avatar');

  if (!trip) {
    return res.status(404).json({ message: 'Trip not found' });
  }

  // Only the trip owner can send invites
  if (trip.createdBy._id.toString() !== req.user._id.toString()) {
    return res.status(403).json({ message: 'Only the trip owner can send invitations' });
  }

  // Check if that email is already a member
  const existingMember = trip.members.find((m) => m.email === normalizedEmail);
  if (existingMember) {
    return res.status(400).json({ message: 'That person is already a member of this trip' });
  }

  // Cancel any existing pending invite for this (trip + email) pair
  await Invitation.updateMany(
    { trip: trip._id, email: normalizedEmail, status: 'pending' },
    { status: 'cancelled' }
  );

  // Create new invitation (token & expiresAt auto-generated by pre-validate hook)
  const invitation = await Invitation.create({
    trip: trip._id,
    invitedBy: req.user._id,
    email: normalizedEmail,
  });

  // Build the accept URL the frontend will handle
  const baseUrl = process.env.INVITE_BASE_URL || process.env.CLIENT_URL || 'http://localhost:5173';
  const inviteUrl = `${baseUrl}/invite/accept?token=${invitation.token}`;

  // Send the email (non-blocking failure — log but don't crash the request)
  try {
    await sendInviteEmail({
      to: normalizedEmail,
      inviterName: req.user.name,
      inviterAvatar: req.user.avatar || null,
      tripName: trip.name,
      currency: trip.currency,
      memberCount: trip.members.length,
      inviteUrl,
    });
  } catch (emailErr) {
    // Email failed — delete the invitation and surface the error
    await Invitation.findByIdAndDelete(invitation._id);
    console.error('Invite email send error:', emailErr.message);
    return res.status(502).json({ message: `Invitation created but email failed to send: ${emailErr.message}` });
  }

  res.status(201).json({
    success: true,
    message: `Invitation sent to ${normalizedEmail}`,
    data: {
      _id: invitation._id,
      email: invitation.email,
      expiresAt: invitation.expiresAt,
      status: invitation.status,
    },
  });
};

// ─── Accept Invite ────────────────────────────────────────────────────────────

// @desc    Accept an invite token — adds the user to the trip
// @route   POST /api/invites/accept
// @access  Private (the invited user must be signed in)
const acceptInvite = async (req, res) => {
  const { token } = req.body;

  if (!token) {
    return res.status(400).json({ message: 'token is required' });
  }

  const invitation = await Invitation.findOne({ token }).populate('trip');

  if (!invitation) {
    return res.status(404).json({ message: 'Invitation not found' });
  }

  if (!invitation.isValid()) {
    const reason =
      invitation.status !== 'pending'
        ? `This invite has already been ${invitation.status}`
        : 'This invite link has expired';
    return res.status(400).json({ message: reason });
  }

  // The signed-in user's email must match the invite email
  if (req.user.email !== invitation.email) {
    return res.status(403).json({
      message: `This invite was sent to ${invitation.email}. Please sign in with that account to accept it.`,
    });
  }

  const trip = await Trip.findById(invitation.trip._id)
    .populate('createdBy', 'name email avatar')
    .populate('members', 'name email avatar');

  if (!trip) {
    return res.status(404).json({ message: 'The trip associated with this invite no longer exists' });
  }

  // Check if already a member (edge case: e.g. was added directly)
  const alreadyMember = trip.members.some((m) => m._id.toString() === req.user._id.toString());
  if (alreadyMember) {
    // Mark invite accepted anyway and return success
    invitation.status = 'accepted';
    invitation.acceptedBy = req.user._id;
    invitation.acceptedAt = new Date();
    await invitation.save();

    return res.json({ success: true, message: 'You are already a member of this trip', data: trip });
  }

  // Add user to trip
  trip.members.push(req.user._id);
  await trip.save();

  // Mark invitation accepted
  invitation.status = 'accepted';
  invitation.acceptedBy = req.user._id;
  invitation.acceptedAt = new Date();
  await invitation.save();

  await trip.populate('members', 'name email avatar');
  await trip.populate('createdBy', 'name email avatar');

  // Notify trip room
  await publishTripEvent(trip._id, 'member_added', { trip, newMember: req.user });

  res.json({
    success: true,
    message: `You've joined "${trip.name}"!`,
    data: trip,
  });
};

// ─── List Invites ─────────────────────────────────────────────────────────────

// @desc    List all invitations for a trip
// @route   GET /api/invites/trips/:tripId
// @access  Private (trip owner)
const listInvites = async (req, res) => {
  const trip = await Trip.findById(req.params.tripId);

  if (!trip) {
    return res.status(404).json({ message: 'Trip not found' });
  }

  if (trip.createdBy.toString() !== req.user._id.toString()) {
    return res.status(403).json({ message: 'Only the trip owner can view invitations' });
  }

  const invitations = await Invitation.find({ trip: trip._id })
    .populate('invitedBy', 'name email avatar')
    .populate('acceptedBy', 'name email avatar')
    .sort({ createdAt: -1 });

  res.json({ success: true, data: invitations });
};

// ─── Cancel Invite ────────────────────────────────────────────────────────────

// @desc    Cancel a pending invite
// @route   DELETE /api/invites/:inviteId
// @access  Private (trip owner)
const cancelInvite = async (req, res) => {
  const invitation = await Invitation.findById(req.params.inviteId).populate('trip');

  if (!invitation) {
    return res.status(404).json({ message: 'Invitation not found' });
  }

  const trip = await Trip.findById(invitation.trip._id || invitation.trip);
  if (!trip) {
    return res.status(404).json({ message: 'Associated trip not found' });
  }

  if (trip.createdBy.toString() !== req.user._id.toString()) {
    return res.status(403).json({ message: 'Only the trip owner can cancel invitations' });
  }

  if (invitation.status !== 'pending') {
    return res.status(400).json({ message: `Cannot cancel an invite that is already "${invitation.status}"` });
  }

  invitation.status = 'cancelled';
  await invitation.save();

  res.json({ success: true, message: 'Invitation cancelled', data: invitation });
};

// ─── Get Invite Info (public — used before user logs in) ──────────────────────

// @desc    Get trip preview info from an invite token (no auth required)
// @route   GET /api/invites/preview?token=xxx
// @access  Public
const previewInvite = async (req, res) => {
  const { token } = req.query;

  if (!token) {
    return res.status(400).json({ message: 'token query param is required' });
  }

  const invitation = await Invitation.findOne({ token })
    .populate('trip', 'name currency members')
    .populate('invitedBy', 'name avatar');

  if (!invitation) {
    return res.status(404).json({ message: 'Invitation not found' });
  }

  if (!invitation.isValid()) {
    return res.status(400).json({
      message: invitation.status !== 'pending'
        ? `This invite has already been ${invitation.status}`
        : 'This invite link has expired',
      status: invitation.status,
    });
  }

  res.json({
    success: true,
    data: {
      tripName: invitation.trip.name,
      currency: invitation.trip.currency,
      memberCount: invitation.trip.members.length,
      invitedBy: invitation.invitedBy,
      expiresAt: invitation.expiresAt,
      email: invitation.email,
    },
  });
};

module.exports = {
  sendInvite,
  acceptInvite,
  listInvites,
  cancelInvite,
  previewInvite,
};
